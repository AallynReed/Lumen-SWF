/// `Character.getType(char)`, from tables dumped from JDK 17 (Unicode 13).
pub fn java_get_type(c: u16) -> i32 {
    let i = JAVA_TYPE_RUNS.partition_point(|&(start, _)| start <= c) - 1;
    JAVA_TYPE_RUNS[i].1 as i32
}

/// `Character.isDefined(char)`.
pub fn java_is_defined(c: u16) -> bool {
    java_get_type(c) != JAVA_UNASSIGNED
}

/// `Character.digit(char, 16)`.
pub fn java_digit16(c: u16) -> i32 {
    for &(start, end, value) in JAVA_HEX_DIGIT_RUNS.iter() {
        if c >= start && c <= end {
            return value as i32 + (c - start) as i32;
        }
    }
    -1
}

/// `Character.isJavaIdentifierPart(char)`.
pub fn java_is_java_identifier_part(c: u16) -> bool {
    match java_get_type(c) {
        JAVA_UPPERCASE_LETTER | JAVA_LOWERCASE_LETTER | JAVA_TITLECASE_LETTER | JAVA_MODIFIER_LETTER
        | JAVA_OTHER_LETTER | JAVA_CURRENCY_SYMBOL | JAVA_CONNECTOR_PUNCTUATION | JAVA_DECIMAL_DIGIT_NUMBER
        | JAVA_LETTER_NUMBER | JAVA_COMBINING_SPACING_MARK | JAVA_NON_SPACING_MARK | JAVA_FORMAT => true,
        _ => c <= 0x08 || (0x0e..=0x1b).contains(&c) || (0x7f..=0x9f).contains(&c),
    }
}

