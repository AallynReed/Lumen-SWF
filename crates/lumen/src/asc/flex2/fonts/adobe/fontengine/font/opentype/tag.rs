    pub fn string2tag(s: &str) -> i32 {
        let units: Vec<u16> = s.encode_utf16().chain("    ".encode_utf16()).collect();
        let mut n: i32 = 0;
        for &u in units.iter().take(4) {
            n = n << 8 | u as i32;
        }
        n
    }

    pub fn tag2string(mut n: i32) -> String {
        let mut c = [0u16; 4];
        for i in (0..4).rev() {
            c[i] = (n & 0xFF) as u16;
            if c[i] == 0 {
                c[i] = 32;
            }
            n >>= 8;
        }
        String::from_utf16_lossy(&c)
    }
