//! The `java.lang.Math` functions `sun.awt.geom` calls, as JDK 17 HotSpot on x86_64 computes them: `min`, `max`,
//! `cos` and `acos` (shared with Marlin), and `pow(x, 1.0 / 3.0)` from the `StubRoutines::dpow` intrinsic.

pub use crate::asc::flex2::fonts::java2d::sun::java2d::marlin::math::{acos, cos};

/// `Math.min(double, double)`.
pub fn min(a: f64, b: f64) -> f64 {
    if a.is_nan() {
        return a;
    }
    if a == 0.0 && b == 0.0 && b.to_bits() == (-0.0f64).to_bits() {
        return b;
    }
    if a <= b {
        a
    } else {
        b
    }
}

/// `Math.max(double, double)`.
pub fn max(a: f64, b: f64) -> f64 {
    if a.is_nan() {
        return a;
    }
    if a == 0.0 && b == 0.0 && a.to_bits() == (-0.0f64).to_bits() {
        return b;
    }
    if a >= b {
        a
    } else {
        b
    }
}

/// `Math.pow(x, 0.3333333333333333)`: the dpow stub (Intel LIBM) replayed lane by lane for positive normal `x`,
/// with Intel's `rcpps` as a table. Zero, infinity and NaN follow `pow`'s special cases; subnormal `x` (never seen
/// from `Order3`) is scaled into range, which may differ from the stub in the last bit.
pub fn pow_one_third(x: f64) -> f64 {
    const Y: f64 = 0.3333333333333333;
    let xb = x.to_bits();
    let h = (xb >> 48) as u32;
    if h.wrapping_sub(0x10) >= 0x7fe0 {
        if x.is_nan() || x == f64::INFINITY || x == 0.0 {
            return if x == 0.0 { 0.0 } else { x };
        }
        if x > 0.0 {
            return pow_one_third(x * f64::from_bits(0x4350000000000000)) * f64::from_bits(0x3ed0000000000000);
        }
        return f64::NAN;
    }
    let near_one = h.wrapping_sub(0x3fef) <= 1;
    let k = ((h as i32) - 0x3ff0) >> 4;
    let s = 31 - ((k.unsigned_abs() + 1).leading_zeros());
    let split_mask = ((0xffff_ffffu32 << s) as u64) << 32;

    let j = rcp_index(((xb >> 41) & 0x7ff) as usize);
    let br = f64::from_bits((((0xfc00 | (j as u64 + 228)) << 14) << 29) & 0xffff_f800_0000_0000);
    let sx = f64::from_bits((xb & 0x000f_ffff_ffff_ffff) | 0x77f0_0000_0000_0000);
    let sx_hi = f64::from_bits(if near_one { sx.to_bits().wrapping_add(0x8000_0000) } else { sx.to_bits() } & split_mask);
    let u = sx_hi * br - f64::from_bits(0x3ff7200000000000);
    let v = (sx - sx_hi) * br;
    let z = v + u;
    let t1 = &LOG_TABLE[j];
    let l_hi = (u + f64::from_bits(t1[0])) + k as f64;
    let l_lo = v + f64::from_bits(t1[1]);
    let c = |i: usize| f64::from_bits(LOG_COEFFS[i]);
    let zz = z * z;
    let z3 = z * zz;
    let z4 = zz * zz;
    let q6 = ((c(4) + c(0) * z) * z3, (c(5) + c(1) * z) * z);
    let q0 = ((c(6) + c(2) * z) * z3, (c(7) + c(3) * z) * z);
    let x3 = (z4 * q6.0 + (q0.0 + l_lo), z4 * q6.1 + q0.1);
    let q = x3.1 + x3.0;

    let yh = f64::from_bits(Y.to_bits() & 0xffff_fff8_0000_0000);
    let yl = Y - yh;
    let a = yh * l_hi;
    let b = yl * l_hi;
    const SHIFTER: f64 = 26388279066624.0;
    let sh = SHIFTER + a;
    let n = sh.to_bits() as u32;
    let f = sh - SHIFTER;
    let r = (a - f) + b;
    let w = Y * q + r;
    let e = (n << 12) & 0xfff0_0000;
    let t2 = &EXP_TABLE[(n & 0xff) as usize];
    let scale = |bits: u64| f64::from_bits(((((bits >> 32) as u32).wrapping_add(e) as u64) << 32) | (bits & 0xffff_ffff));
    let (tlo, thi) = (scale(t2[0]), scale(t2[1]));
    let ec = |i: usize| f64::from_bits(EXP_COEFFS[i]);
    let w2 = w * w;
    let w4 = w2 * w2;
    let r1 = f64::from_bits(0x3fe62e42fefa39ef) * w * tlo + thi;
    let s0 = w4 * (ec(2) + ec(0) * w) * tlo;
    let s3 = w2 * (ec(3) + ec(1) * w) * tlo;
    ((s0 + r1) + s3) + tlo
}

/// The `LOG_TABLE` row `rcpps(1.m) * 1.4453125f`, rounded to 9 mantissa bits, selects for the top 11 mantissa bits:
/// 512 minus the number of steps set up to `m11`.
fn rcp_index(m11: usize) -> usize {
    let w = m11 >> 6;
    let mut n = (RCP_STEPS[w] & (u64::MAX >> (63 - (m11 & 63)))).count_ones();
    for v in &RCP_STEPS[..w] {
        n += v.count_ones();
    }
    512 - n as usize
}

