//! Port of `flex2.compiler.mxml.builder.PrimitiveBuilder`.

use super::abstract_builder::{analyzer_basics, attr_str, err, AbstractBuilder, BindingHandlerKind, Builder, BuilderContext};
use crate::asc::flex2::compiler::mxml::dom::analyzer::Analyzer;
use crate::asc::flex2::compiler::mxml::dom::node::NodeRef;
use crate::asc::flex2::compiler::mxml::lang::standard_defs as sd;
use crate::asc::flex2::compiler::mxml::lang::text_parser;
use crate::asc::flex2::compiler::mxml::reflect::{Assignable, Stateful, TypeRef};
use crate::asc::flex2::compiler::mxml::rep::model::{Model, ModelRef, RValue};
use crate::asc::flex2::compiler::util::name_formatter;

pub struct PrimitiveBuilder {
    pub ab: AbstractBuilder,
    parent: Option<ModelRef>,
    top_level: bool,
    binding_handler: Option<BindingHandlerKind>,
    pub value: Option<ModelRef>,
    property: Option<Assignable>,
}

impl PrimitiveBuilder {
    /// `new PrimitiveBuilder(unit, typeTable, mxmlConfiguration, document, parent, topLevel, property, bindingHandler)`.
    pub fn new(ctx: &BuilderContext, parent: Option<ModelRef>, top_level: bool, property: Option<Assignable>, binding_handler: Option<BindingHandlerKind>) -> PrimitiveBuilder {
        PrimitiveBuilder { ab: AbstractBuilder::new(ctx), parent, top_level, binding_handler, value: None, property }
    }

    fn process_primitive_entry(&mut self, node: &NodeRef) {
        let t = self.ab.resolve_type(node).expect("NullPointerException");
        let primitive = self.init_primitive_value(&t, node);
        let cdata = if node.borrow().is_cdata_node() {
            Some(node.clone())
        } else {
            let children = node.borrow().get_children();
            self.get_text_content(&children, false)
        };
        let line = node.borrow().begin_line;
        match cdata {
            Some(cdata) => {
                let (image, in_cdata, cline) = {
                    let c = cdata.borrow();
                    (c.image.clone(), c.in_cdata(), c.begin_line)
                };
                self.process_text_initializer(&image, &t, in_cdata, cline);
            }
            None => {
                if !self.top_level {
                    if self.ab.type_table.string_type().is_assignable_to(Some(&t)) {
                        self.process_text_initializer("", &t, true, line);
                    } else {
                        self.ab.log_line(line, err("Initializer value is required here.", &[]));
                    }
                }
            }
        }
        self.process_state_attributes(node, &primitive);
        let mut id = attr_str(self.get_language_attribute_value(node, sd::PROP_ID));
        if id.is_some() || self.top_level || primitive.is_declaration_ensured() {
            let comment = {
                let mut n = node.borrow_mut();
                n.comment.get_or_insert_with(String::new).clone()
            };
            if primitive.get_value().is_some() {
                *primitive.comment.borrow_mut() = Some(comment);
                self.ab.register_model_id(id.as_deref(), &primitive, self.top_level);
            } else {
                let mut autogenerated = false;
                if id.is_none() {
                    autogenerated = true;
                    id = primitive.get_id();
                }
                self.ab.document.add_declaration_named(&id.unwrap_or_default(), &t.get_name(), line, true, self.top_level, autogenerated, primitive.get_bindability_ensured(), Some(&comment));
            }
        }
    }

    fn init_primitive_value(&mut self, t: &TypeRef, node: &NodeRef) -> ModelRef {
        let primitive = Model::new_primitive(&self.ab.document, t.clone(), self.parent.clone(), node.borrow().begin_line);
        primitive.set_inspectable(true);
        if let Some(p) = &self.property {
            primitive.set_parent_index_state(p.get_name().as_deref(), p.get_state_name().as_deref());
        }
        self.value = Some(primitive.clone());
        primitive
    }

    /// `processTextInitializer(text, type, cdata, line)`.
    pub fn process_text_initializer(&mut self, text: &str, t: &TypeRef, cdata: bool, line: i32) {
        let mut flags = if cdata { text_parser::FLAG_IN_CDATA } else { 0 };
        if let Some(Assignable::Property(p)) = &self.property {
            if p.rich_text_content() {
                flags |= text_parser::FLAG_RICH_TEXT_CONTENT;
            }
        }
        let result = self.ab.text_parser.parse_value_simple(text, t, flags, line, &name_formatter::to_dot(&t.get_name()));
        if let Some(result) = result {
            let value = self.value.clone().expect("value");
            if let RValue::Binding(be) = &result {
                match &self.binding_handler {
                    Some(h) => {
                        h.invoke(be, &value);
                    }
                    None => self.ab.log_current(err("Data binding expression not allowed here.", &[])),
                }
            }
            value.set_value(Some(result));
        }
    }
}

impl Builder for PrimitiveBuilder {
    fn ab(&mut self) -> &mut AbstractBuilder {
        &mut self.ab
    }

    fn abr(&self) -> &AbstractBuilder {
        &self.ab
    }
}

impl Analyzer for PrimitiveBuilder {
    analyzer_basics!();

    fn analyze_string_node(&mut self, node: &NodeRef) {
        self.process_primitive_entry(node);
    }

    fn analyze_number_node(&mut self, node: &NodeRef) {
        self.process_primitive_entry(node);
    }

    fn analyze_int_node(&mut self, node: &NodeRef) {
        self.process_primitive_entry(node);
    }

    fn analyze_uint_node(&mut self, node: &NodeRef) {
        self.process_primitive_entry(node);
    }

    fn analyze_boolean_node(&mut self, node: &NodeRef) {
        self.process_primitive_entry(node);
    }

    fn analyze_class_node(&mut self, node: &NodeRef) {
        self.process_primitive_entry(node);
    }

    fn analyze_function_node(&mut self, node: &NodeRef) {
        self.process_primitive_entry(node);
    }

    fn analyze_cdata_node(&mut self, node: &NodeRef) {
        self.process_primitive_entry(node);
    }
}
