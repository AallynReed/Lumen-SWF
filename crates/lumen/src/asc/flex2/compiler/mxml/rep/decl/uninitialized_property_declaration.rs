//! Port of `flex2.compiler.mxml.rep.decl.UninitializedPropertyDeclaration`.

use crate::asc::flex2::compiler::util::name_formatter;

#[derive(Clone, Debug)]
pub struct UninitializedPropertyDeclaration {
    name: String,
    type_name: String,
    line_ref: i32,
    inspectable: bool,
    top_level: bool,
    id_is_autogenerated: bool,
    bindability_ensured: bool,
    comment: Option<String>,
}

impl UninitializedPropertyDeclaration {
    #[allow(clippy::too_many_arguments)]
    pub fn new(name: &str, type_name: &str, line_ref: i32, inspectable: bool, top_level: bool, id_is_autogenerated: bool, is_bindable: bool, comment: Option<&str>) -> UninitializedPropertyDeclaration {
        UninitializedPropertyDeclaration {
            name: name.to_string(),
            type_name: type_name.to_string(),
            line_ref,
            inspectable,
            top_level,
            id_is_autogenerated,
            bindability_ensured: is_bindable,
            comment: comment.map(Into::into),
        }
    }

    pub fn get_line_ref(&self) -> i32 {
        self.line_ref
    }

    pub fn get_name(&self) -> &str {
        &self.name
    }

    pub fn get_type_expr(&self) -> String {
        name_formatter::to_dot(&self.type_name)
    }

    pub fn get_inspectable(&self) -> bool {
        self.inspectable
    }

    pub fn get_top_level(&self) -> bool {
        self.top_level
    }

    pub fn get_id_is_autogenerated(&self) -> bool {
        self.id_is_autogenerated
    }

    pub fn get_bindability_ensured(&self) -> bool {
        self.bindability_ensured
    }

    pub fn get_comment(&self) -> Option<&str> {
        self.comment.as_deref()
    }
}
