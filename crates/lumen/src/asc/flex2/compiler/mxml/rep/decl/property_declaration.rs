//! Port of `flex2.compiler.mxml.rep.decl.PropertyDeclaration`: an `InitializedPropertyDeclaration` (an initializer)
//! or an `UninitializedPropertyDeclaration`. Exposed to `ClassDef.vm` as the Java class it wraps.

use std::rc::Rc;

use super::uninitialized_property_declaration::UninitializedPropertyDeclaration;
use crate::asc::flex2::compiler::mxml::rep::init::initializer::InitializerRef;
use crate::asc::flex2::velocity::{JType, JavaException, JavaObject, Method, Value};

#[derive(Clone)]
pub enum PropertyDeclaration {
    Initialized(InitializerRef),
    Uninitialized(Rc<UninitializedPropertyDeclaration>),
}

impl PropertyDeclaration {
    /// The initializer of an `InitializedPropertyDeclaration` (`decl instanceof ValueInitializer`).
    pub fn as_initializer(&self) -> Option<&InitializerRef> {
        match self {
            PropertyDeclaration::Initialized(i) => Some(i),
            PropertyDeclaration::Uninitialized(_) => None,
        }
    }

    pub fn get_line_ref(&self) -> i32 {
        match self {
            PropertyDeclaration::Initialized(i) => i.get_line_ref(),
            PropertyDeclaration::Uninitialized(u) => u.get_line_ref(),
        }
    }

    pub fn get_name(&self) -> String {
        match self {
            PropertyDeclaration::Initialized(i) => i.get_name(),
            PropertyDeclaration::Uninitialized(u) => u.get_name().to_string(),
        }
    }

    pub fn get_type_expr(&self) -> String {
        match self {
            PropertyDeclaration::Initialized(i) => i.as_value().unwrap().get_type_expr(),
            PropertyDeclaration::Uninitialized(u) => u.get_type_expr(),
        }
    }

    pub fn get_inspectable(&self) -> bool {
        match self {
            PropertyDeclaration::Initialized(i) => i.as_value().and_then(|v| v.get_model()).is_some_and(|m| m.get_inspectable()),
            PropertyDeclaration::Uninitialized(u) => u.get_inspectable(),
        }
    }

    pub fn get_top_level(&self) -> bool {
        match self {
            PropertyDeclaration::Initialized(i) => i.as_value().unwrap().get_top_level(),
            PropertyDeclaration::Uninitialized(u) => u.get_top_level(),
        }
    }

    pub fn get_id_is_autogenerated(&self) -> bool {
        match self {
            PropertyDeclaration::Initialized(i) => i.as_value().and_then(|v| v.get_model()).is_some_and(|m| m.get_id_is_autogenerated()),
            PropertyDeclaration::Uninitialized(u) => u.get_id_is_autogenerated(),
        }
    }

    pub fn get_bindability_ensured(&self) -> bool {
        match self {
            PropertyDeclaration::Initialized(i) => i.as_value().and_then(|v| v.get_model()).is_some_and(|m| m.get_bindability_ensured()),
            PropertyDeclaration::Uninitialized(u) => u.get_bindability_ensured(),
        }
    }

    pub fn get_comment(&self) -> Option<String> {
        match self {
            PropertyDeclaration::Initialized(i) => i.as_value().and_then(|v| v.get_comment()),
            PropertyDeclaration::Uninitialized(u) => u.get_comment().map(Into::into),
        }
    }

    pub fn value(&self) -> Value {
        Value::Object(Rc::new(self.clone()))
    }
}

static METHODS: &[Method] = &[
    Method::new("getLineRef", &[], JType::Int),
    Method::new("getName", &[], JType::String),
    Method::new("getTypeExpr", &[], JType::String),
    Method::new("getInspectable", &[], JType::Boolean),
    Method::new("getTopLevel", &[], JType::Boolean),
    Method::new("getIdIsAutogenerated", &[], JType::Boolean),
    Method::new("getBindabilityEnsured", &[], JType::Boolean),
    Method::new("getComment", &[], JType::String),
];

impl JavaObject for PropertyDeclaration {
    fn class_name(&self) -> &str {
        match self {
            PropertyDeclaration::Initialized(_) => "flex2.compiler.mxml.rep.decl.InitializedPropertyDeclaration",
            PropertyDeclaration::Uninitialized(_) => "flex2.compiler.mxml.rep.decl.UninitializedPropertyDeclaration",
        }
    }

    fn instance_of(&self, class_name: &str) -> bool {
        class_name == self.class_name() || class_name == "flex2.compiler.mxml.rep.decl.PropertyDeclaration"
    }

    fn methods(&self) -> &[Method] {
        METHODS
    }

    fn invoke(&self, method: &Method, _args: &[Value]) -> Result<Value, JavaException> {
        Ok(match &*method.name {
            "getLineRef" => Value::Integer(self.get_line_ref()),
            "getName" => Value::str(&self.get_name()),
            "getTypeExpr" => Value::str(&self.get_type_expr()),
            "getInspectable" => Value::Boolean(self.get_inspectable()),
            "getTopLevel" => Value::Boolean(self.get_top_level()),
            "getIdIsAutogenerated" => Value::Boolean(self.get_id_is_autogenerated()),
            "getBindabilityEnsured" => Value::Boolean(self.get_bindability_ensured()),
            "getComment" => self.get_comment().map_or(Value::Null, |c| Value::str(&c)),
            _ => Value::Null,
        })
    }
}
